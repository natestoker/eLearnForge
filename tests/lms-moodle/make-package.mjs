import { fileURLToPath } from 'node:url'; const ROOT = fileURLToPath(new URL('../..', import.meta.url)).replace(/\/$/, '');
import { createRequire as cr } from 'node:module'; const { build } = cr(ROOT + '/package.json')('esbuild');
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
const root = ROOT;
const require = createRequire(ROOT + '/package.json');
const JSZip = require('jszip');
const out = process.argv[2] + '/m.cjs';
await build({ entryPoints: [ROOT + '/src/publish/manifests.ts'], bundle: true, platform: 'node', format: 'cjs', outfile: out, logLevel: 'error' });
await build({ entryPoints: [ROOT + '/src/schema/factory.ts'], bundle: true, platform: 'node', format: 'cjs', outfile: process.argv[2] + '/f.cjs', logLevel: 'error' });
const m = require(out), f = require(process.argv[2] + '/f.cjs');
const p = f.createDemoProject(); p.player = { ...f.defaultPlayerSettings(), ...(p.player ?? {}) };
p.completion = { mode: 'allSlides', autoScore: true, passingScore: 50 };
const target = process.argv[3];
const html = readFileSync(ROOT + '/dist/player.html', 'utf8').replace('<head>', `<head>\n<script>window.FORGE_PUBLISH = { target: "${target}" };</script>\n<script id="forge-project" type="application/json">${JSON.stringify(p).replace(/</g, '\\u003c')}</script>\n`);
const z = new JSZip(); z.file('index.html', html);
z.file('imsmanifest.xml', (target === 'scorm12' ? m.scorm12Manifest : m.scorm2004Manifest)(p.title, 50));
writeFileSync(process.argv[2] + `/${target}.zip`, await z.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' }));
console.log('ok');
